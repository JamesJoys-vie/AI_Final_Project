"""Fixed game scenarios so all 4 search configurations are compared on exactly the same states."""
from __future__ import annotations

from typing import Dict

from task2_tank_battle.core.actions import Direction
from task2_tank_battle.core.entities import Bullet
from task2_tank_battle.core.game_state import GameState
from task2_tank_battle.core.map_loader import MapLoader

DUEL_MAP = """
.....#B#.....
.....###.....
.............
..##.....##..
......2......
....#...#....
.............
....#...#....
......1......
..##.....##..
.............
.....###.....
.....#A#.....
"""

SIEGE_MAP = """
.....#B#.....
.....#.#.....
....1........
.#.#.#.#.#.#.
.....#.#.....
##.##...##.##
.....#.#.....
##.##...##.##
.....#.#.....
.#.#.#.#.#.#.
........2....
.....#.#.....
.....#A#.....
"""


def build_scenarios() -> Dict[str, GameState]:
    """
    opening = start of the classic map, duel = tanks face each other at close range (P2 has 4 HP),
    siege = both bases half open with tanks next to them (P1 base has 6 HP), bullets = shots in the air.
    """
    opening = MapLoader.load("classic")
    # Small HP differences break the symmetry, so EVAL is not trivially 0.
    duel = MapLoader.parse(DUEL_MAP)
    duel.tanks = (duel.tanks[0], duel.tanks[1]._replace(hp=4))
    siege = MapLoader.parse(SIEGE_MAP)
    siege.bases = (siege.bases[0]._replace(hp=6), siege.bases[1])

    base = MapLoader.parse(DUEL_MAP)
    p1, p2 = base.tanks
    bullets = (Bullet(1, p2.x, p2.y + 1, Direction.DOWN), Bullet(0, 2, p2.y, Direction.RIGHT))
    in_flight = GameState(base.width, base.height, base.walls,
                          (p1._replace(hp=4), p2._replace(hp=5)), base.bases, bullets)
    return {"opening": opening, "duel": duel, "siege": siege, "bullets": in_flight}
